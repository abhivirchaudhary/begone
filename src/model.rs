//! Core data types shared by the scanners, the safety layer, the engine and the UI.

use std::path::PathBuf;
use std::time::{Duration, SystemTime};

use crate::safety::Grant;

/// What kind of thing an item is. Declared in ring order: the hues run gold to
/// pink around the donut, so it reads as one corona.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Kind {
    Caches,
    Logs,
    Trash,
    Developer,
    Xcode,
    /// An app and the traces it left. Never part of the cleaning panel: apps are chosen on their own tab.
    Apps,
    /// Old installers and iPhone backups. Never part of the cleaning panel either: they are chosen on the Files tab.
    Files,
}

impl Kind {
    pub const ALL: [Kind; 7] = [Kind::Caches, Kind::Logs, Kind::Trash, Kind::Developer, Kind::Xcode, Kind::Apps, Kind::Files];
    /// How many kinds there are, for the arrays that hold one value of each.
    pub const COUNT: usize = 7;

    pub fn index(self) -> usize {
        self as usize
    }

    /// Stable name written to the undo history.
    pub fn key(self) -> &'static str {
        match self {
            Kind::Caches => "caches",
            Kind::Logs => "logs",
            Kind::Trash => "trash",
            Kind::Developer => "developer",
            Kind::Xcode => "xcode",
            Kind::Apps => "apps",
            Kind::Files => "files",
        }
    }

    pub fn from_key(key: &str) -> Option<Kind> {
        Kind::ALL.into_iter().find(|k| k.key() == key)
    }

    pub fn label(self) -> &'static str {
        match self {
            Kind::Caches => "Caches",
            Kind::Logs => "Old logs",
            Kind::Trash => "Already in Trash",
            Kind::Developer => "Build artifacts",
            Kind::Xcode => "Xcode",
            Kind::Apps => "Apps",
            Kind::Files => "Files",
        }
    }
}

/// How a list is ordered. The lists come biggest-first by default, because space is the point; `s` cycles through the others.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
pub enum SortBy {
    /// Biggest first.
    #[default]
    Size,
    /// A to Z.
    Name,
    /// Oldest first — the stalest things, the ones most likely safe to let go, at the top.
    Date,
}

impl SortBy {
    pub fn next(self) -> SortBy {
        match self {
            SortBy::Size => SortBy::Name,
            SortBy::Name => SortBy::Date,
            SortBy::Date => SortBy::Size,
        }
    }

    /// The word shown for the current order.
    pub fn label(self) -> &'static str {
        match self {
            SortBy::Size => "size",
            SortBy::Name => "name",
            SortBy::Date => "oldest",
        }
    }
}

/// How confident we are that removing an item is harmless.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum SafetyClass {
    /// Regenerated by the OS or an app with no visible effect.
    Safe,
    /// Comes back the next time the relevant tool runs, at some cost in time.
    Rebuildable,
    /// Made by you or for you. begone cannot tell whether you still need it, so it only lists it.
    Yours,
}

/// The word shown beside a row: what happens if it goes, in as few words as possible.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Tag {
    Safe,
    Rebuilds,
    InUse,
    Running,
    System,
    Yours,
}

impl Tag {
    pub fn label(self) -> &'static str {
        match self {
            Tag::Safe => "safe",
            Tag::Rebuilds => "rebuilds",
            Tag::InUse => "recent",
            Tag::Running => "running",
            Tag::System => "system",
            Tag::Yours => "yours",
        }
    }
}

/// One reason begone believes what it says about an item. The inspector shows
/// these, so nobody has to take a label on faith.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Evidence {
    pub ok: bool,
    pub text: String,
}

impl Evidence {
    pub fn good(text: impl Into<String>) -> Self {
        Self { ok: true, text: text.into() }
    }
    pub fn warn(text: impl Into<String>) -> Self {
        Self { ok: false, text: text.into() }
    }
}

/// One thing begone could remove: a directory taken wholesale, or a single file.
#[derive(Clone, Debug)]
pub struct ScanItem {
    /// Stable for the life of the scan. Rows, results and selection key on this.
    pub id: u64,
    pub path: PathBuf,
    /// Bytes that removing this would really free: allocated blocks, with hard
    /// links and APFS clones counted once across the whole scan.
    pub size: u64,
    pub files: u64,
    pub kind: Kind,
    pub safety: SafetyClass,
    pub tag: Tag,
    /// Which safety gate admits this item. The deleter re-runs that gate.
    pub grant: Grant,
    /// Row label, such as `node_modules/`.
    pub title: String,
    /// Where it comes from: the project, or the app.
    pub source: String,
    pub what: String,
    pub comes_back: String,
    pub evidence: Vec<Evidence>,
    /// The newest modification anywhere inside it, so it means "last used".
    pub modified: Option<SystemTime>,
    pub pre_selected: bool,
    /// For an item that belongs to an app: the app's bundle identifier. The gate for app items checks the path against it.
    pub owner: Option<String>,
    /// The person asked begone to keep it: it is shown, never chosen and never moved.
    pub kept: bool,
}

impl ScanItem {
    /// How long since anything inside this item changed.
    pub fn idle(&self) -> Option<Duration> {
        idle_since(self.modified)
    }

    /// `~/Library/Caches/foo` rather than the full path, given the home folder.
    pub fn short_path(&self, home: &std::path::Path) -> String {
        match self.path.strip_prefix(home) {
            Ok(rest) => format!("~/{}", rest.display()),
            Err(_) => self.path.display().to_string(),
        }
    }
}

pub fn idle_since(modified: Option<SystemTime>) -> Option<Duration> {
    let then = modified?;
    Some(SystemTime::now().duration_since(then).unwrap_or_default())
}

/// A short age: `today`, `41 d`, `8 mo`, `2 yr`.
pub fn human_age(idle: Option<Duration>) -> String {
    let Some(idle) = idle else { return "—".to_string() };
    let days = idle.as_secs() / 86_400;
    match days {
        0 => "today".to_string(),
        1..=89 => format!("{days} d"),
        90..=719 => format!("{} mo", days / 30),
        _ => format!("{} yr", days / 365),
    }
}

/// Number and unit separately, in decimal units so figures match Finder's.
pub fn human_parts(bytes: u64) -> (String, &'static str) {
    human_parts_in(bytes as f64, bytes)
}

/// `value` bytes written in the unit that `reference` bytes would be written in. A number that is counting down keeps the unit
/// it started in this way, instead of running on through the smaller ones as 842, 300, 40, 1, 800, 40, 1, 600.
pub fn human_parts_in(value: f64, reference: u64) -> (String, &'static str) {
    const KB: f64 = 1_000.0;
    const MB: f64 = 1_000_000.0;
    const GB: f64 = 1_000_000_000.0;
    const TB: f64 = 1_000_000_000_000.0;
    let r = reference as f64;
    // Nothing is written as 0, not 0.0 or 0.00, so a count down lands on the same figure it was heading for.
    let decimals = |n: f64, places: usize| if n < 0.5 * 10f64.powi(-(places as i32)) { "0".to_string() } else { format!("{n:.places$}") };
    if r >= TB {
        (decimals(value / TB, 2), "TB")
    } else if r >= GB {
        (decimals(value / GB, 1), "GB")
    } else if r >= MB {
        (format!("{:.0}", value / MB), "MB")
    } else if r >= KB {
        (format!("{:.0}", value / KB), "KB")
    } else {
        (format!("{}", value.round() as u64), "B")
    }
}

/// A size as a person types it: a number and an optional unit (`20`, `20 GB`, `1.5tb`, `500m`). A bare number is gigabytes.
pub fn parse_size(text: &str) -> Option<u64> {
    let text = text.trim().to_lowercase().replace(',', ".");
    let split = text.find(|c: char| !(c.is_ascii_digit() || c == '.')).unwrap_or(text.len());
    let (number, unit) = text.split_at(split);
    let number: f64 = number.parse().ok()?;
    let times = match unit.trim() {
        "" | "g" | "gb" => 1e9,
        "m" | "mb" => 1e6,
        "k" | "kb" => 1e3,
        "t" | "tb" => 1e12,
        "b" => 1.0,
        _ => return None,
    };
    let bytes = number * times;
    (bytes.is_finite() && (1.0..=1e14).contains(&bytes)).then_some(bytes as u64)
}

pub fn human(bytes: u64) -> String {
    let (n, u) = human_parts(bytes);
    format!("{n} {u}")
}

/// `1,204,388`
pub fn commas(n: u64) -> String {
    let s = n.to_string();
    let mut out = String::with_capacity(s.len() + s.len() / 3);
    for (i, c) in s.chars().enumerate() {
        if i > 0 && (s.len() - i).is_multiple_of(3) {
            out.push(',');
        }
        out.push(c);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_number_can_be_written_in_the_unit_of_another_so_a_count_down_never_changes_unit() {
        // Counting down from 842 MB: every step stays in MB, and ends on 0.
        for (value, want) in [
            (842_000_000.0, "842"),
            (300_000_000.0, "300"),
            (40_400_000.0, "40"),
            (1_200_000.0, "1"),
            (800_000.0, "1"),
            (600.0, "0"),
            (0.0, "0"),
        ] {
            assert_eq!(human_parts_in(value, 842_000_000), (want.to_string(), "MB"), "{value}");
        }
        assert_eq!(human_parts_in(432_000_000.0, 10_700_000_000), ("0.4".to_string(), "GB"));
        assert_eq!(human_parts_in(1_500.0, 11_000_000_000_000), ("0".to_string(), "TB"));
        assert_eq!(human_parts_in(20_000_000.0, 3_500_000_000), ("0".to_string(), "GB"), "0.02 GB is shown as 0, not 0.0");
        assert_eq!(human_parts_in(60_000_000.0, 3_500_000_000), ("0.1".to_string(), "GB"));
        assert_eq!(human_parts_in(0.0, 3_500_000_000), ("0".to_string(), "GB"));
        assert_eq!(human_parts_in(3.6, 900), ("4".to_string(), "B"));
        assert_eq!(human_parts_in(0.0, 0), ("0".to_string(), "B"));
        // On its own it is what it always was.
        for bytes in [0u64, 999, 1_000, 999_999, 1_000_000, 842_129_216, 1_000_000_000, 11_207_999_488, 2_000_000_000_000] {
            assert_eq!(human_parts(bytes), human_parts_in(bytes as f64, bytes), "{bytes}");
        }
        assert_eq!(human_parts(842_129_216), ("842".to_string(), "MB"));
        assert_eq!(human_parts(11_207_999_488), ("11.2".to_string(), "GB"));
    }

    #[test]
    fn a_typed_size_is_a_number_and_an_optional_unit_and_a_bare_number_is_gigabytes() {
        for (typed, want) in [
            ("20", Some(20_000_000_000)),
            ("20 GB", Some(20_000_000_000)),
            ("20gb", Some(20_000_000_000)),
            ("  20 g ", Some(20_000_000_000)),
            ("1.5 tb", Some(1_500_000_000_000)),
            ("1,5 GB", Some(1_500_000_000)),
            (".5g", Some(500_000_000)),
            ("500 MB", Some(500_000_000)),
            ("500m", Some(500_000_000)),
            ("64 kb", Some(64_000)),
            ("900 B", Some(900)),
            ("0", None),
            ("0 GB", None),
            ("", None),
            ("   ", None),
            ("GB", None),
            ("-5", None),
            ("1.2.3 GB", None),
            ("20 gigs", None),
            ("20 parsecs", None),
            ("999999 TB", None),
        ] {
            assert_eq!(parse_size(typed), want, "{typed:?}");
        }
    }

    #[test]
    fn sizes_use_decimal_units_like_finder() {
        assert_eq!(human(0), "0 B");
        assert_eq!(human(999), "999 B");
        assert_eq!(human(4_096), "4 KB");
        assert_eq!(human(812_000_000), "812 MB");
        assert_eq!(human(148_600_000_000), "148.6 GB");
        assert_eq!(human(2_500_000_000_000), "2.50 TB");
    }

    #[test]
    fn ages_stay_short_enough_for_a_column() {
        assert_eq!(human_age(None), "—");
        assert_eq!(human_age(Some(Duration::from_secs(3_600))), "today");
        assert_eq!(human_age(Some(Duration::from_secs(41 * 86_400))), "41 d");
        assert_eq!(human_age(Some(Duration::from_secs(240 * 86_400))), "8 mo");
        assert_eq!(human_age(Some(Duration::from_secs(800 * 86_400))), "2 yr");
    }

    #[test]
    fn large_counts_get_separators() {
        assert_eq!(commas(1_204_388), "1,204,388");
        assert_eq!(commas(999), "999");
    }
}

/// `3 hours ago`, `41 days ago`, `8 months ago`: a sentence-sized age.
pub fn ago(idle: Duration) -> String {
    let secs = idle.as_secs();
    let (n, unit) = if secs < 3_600 {
        ((secs / 60).max(1), "minute")
    } else if secs < 86_400 {
        (secs / 3_600, "hour")
    } else if secs < 86_400 * 60 {
        (secs / 86_400, "day")
    } else if secs < 86_400 * 730 {
        (secs / (86_400 * 30), "month")
    } else {
        (secs / (86_400 * 365), "year")
    };
    format!("{n} {unit}{} ago", if n == 1 { "" } else { "s" })
}

